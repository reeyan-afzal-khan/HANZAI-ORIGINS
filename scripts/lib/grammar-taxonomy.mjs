const ALL = { ...DETAIL_EN, ...CATEGORY_EN, ...PHRASE_CATEGORY_EN }

/** Translate a taxonomy label, falling back to the original Chinese. */
export function tx(label) {
  if (!label) return ''
  const key = label.trim()
  return ALL[key] || ALL[key.replace(/\s+/g, ' ')] || label.replace(/\s+/g, ' ')
}
