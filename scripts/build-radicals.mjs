/**
 * The radical index, as a dictionary has it: every character filed under the
 * radical it is written with, the radicals in order of their strokes, and a
 * radical's characters in order of the strokes left once it is taken away.
 *
 *   npm run radicals
 *
 *   data/dictionary/radicals.json   the radicals as written: strokes, Kangxi number, name
 *   data/hskker.db                  the characters (npm run db)
 *          ──>  app/data/radicals.js
 *
 * A character's radical is recorded two ways: its Kangxi radical (hanziDB) in
 * the full form — 水 for 汉, 言 for 说 — and, for about half, the radical a
 * modern dictionary files it under (CC-CEDICT's), as it is written — 氵, 讠.
 * The index is of written forms, as Pleco's is. A character goes under
 * CC-CEDICT's radical where there is one; otherwise under whichever of its
 * parts is a written form of its Kangxi radical; otherwise under the Kangxi
 * radical itself. A form recorded in its traditional shape is filed under the
 * simplified one (貝 under 贝), and ⺼ under 月, the way it is written.
 *
 * Checked as it goes: every character has to land on a radical in the table,
 * and a radical that is also a character in the list has to have that
 * character's stroke count. Either failing stops the build.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { openDb, rows, shardOf, shardName } from './lib/db.mjs'
import { DICT } from './lib/paths.mjs'

const table = JSON.parse(readFileSync(DICT.radicals, 'utf8'))
const written = (f) => table.written[f] || f
const forms = new Map(table.forms.map((x) => [x.f, x]))
/* Kangxi number -> the forms written for it (水: 水 氵) */
const ofKangxi = new Map()
for (const x of table.forms) {
  for (const k of x.k) {
    if (!ofKangxi.has(k)) ofKangxi.set(k, new Set())
    ofKangxi.get(k).add(x.f)
  }
}

const db = openDb()
const chars = rows(db, `SELECT hanzi, level, rank, stroke_count, radical, radical_no, cedict_radical, components
  FROM chars ORDER BY ord`)
if (!chars.length) throw new Error('data/hskker.db has no characters — run `npm run db`')

/* hanziDB has no stroke count for a few characters (范). The stroke-order
   data the app ships has every stroke of them, so the count is taken from
   there (npm run strokes). */
function strokesDrawn(h) {
  const file = `app/data/strokes/${shardName(shardOf(h))}.js`
  if (!existsSync(file)) return null
  let shard = null
  const HSKSTROKE = { shard: (n, m) => { shard = m } }
  new Function('HSKSTROKE', readFileSync(file, 'utf8'))(HSKSTROKE)
  return shard && shard[h] ? shard[h].strokes.length : null
}
for (const c of chars) if (!c.stroke_count) c.stroke_count = strokesDrawn(c.hanzi)

/* The written radical a character is filed under, and the spelling it was
   recorded in. */
function radicalOf(c) {
  if (c.cedict_radical) return [written(c.cedict_radical), c.cedict_radical]
  const own = ofKangxi.get(c.radical_no) || new Set()
  for (const p of c.components) if (own.has(written(p.c))) return [written(p.c), p.c]
  return [written(c.radical), c.radical]
}

const problems = []
const filed = new Map()     // radical -> its characters
const spelt = new Map()     // radical -> the other spellings it was recorded in (⺼ for 月)
for (const c of chars) {
  const [f, as] = radicalOf(c)
  const x = forms.get(f)
  if (!x) { problems.push(`${c.hanzi}: its radical ${f} is not in radicals.json`); continue }
  const rest = c.stroke_count - x.s
  if (rest < 0) problems.push(`${c.hanzi}: ${c.stroke_count} strokes, fewer than its radical ${f} has (${x.s})`)
  if (!filed.has(f)) filed.set(f, [])
  filed.get(f).push({ h: c.hanzi, rest: Math.max(0, rest), level: +c.level, rank: c.rank ?? 1e9 })
  if (as !== f) {
    if (!spelt.has(f)) spelt.set(f, new Set())
    spelt.get(f).add(as)
  }
}
const strokes = new Map(chars.map((c) => [c.hanzi, c.stroke_count]))
for (const x of table.forms) {
  if (strokes.has(x.f) && strokes.get(x.f) !== x.s)
    problems.push(`${x.f}: ${x.s} strokes in radicals.json, ${strokes.get(x.f)} in the character list`)
}
if (problems.length) throw new Error(`radicals.json does not fit the characters:\n  ${problems.join('\n  ')}`)

/* Fewest strokes first, and within a count in Kangxi order, a written form
   beside its full one (人 亻). A radical's characters by the strokes left,
   then by level, then the commonest first. Radicals no character is filed
   under are left out. */
const index = table.forms
  .filter((x) => filed.has(x.f))
  .sort((a, b) => a.s - b.s || a.k[0] - b.k[0])
  .map((x) => {
    const list = filed.get(x.f).sort((a, b) => a.rest - b.rest || a.level - b.level || a.rank - b.rank)
    return [x.f, x.s, x.en, list.map((c) => c.h).join(''), list.map((c) => c.rest), [...(spelt.get(x.f) || [])].join('')]
  })

writeFileSync('app/data/radicals.js',
  '/* Generated by scripts/build-radicals.mjs from data/dictionary/radicals.json — not edited by hand.\n' +
  '   Each radical: [as written, strokes, name, its characters, the strokes left in each, other spellings]. */\n' +
  `HSKDATA("radicals",${JSON.stringify(index)});\n`)
const filedN = index.reduce((n, r) => n + [...r[3]].length, 0)
console.log(`app/data/radicals.js  ${index.length} radicals, ${filedN} characters filed`)
