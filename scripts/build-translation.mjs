/**
 * The offline translator, into the app: `npm run translation`.
 *
 * What the reader's "Compact" translator is made of — the Transformers.js
 * runtime and OPUS-MT zho-eng — is listed once, in data/translation/
 * files.json: each file's name, where it comes from (pinned to one release),
 * its size and its SHA-256.
 *
 * 1. Fetches every file into data/translation/, exactly as published and
 *    checked against its checksum. A file already there and whole is not
 *    fetched again.
 *
 * 2. Writes app/data/translation-files.js: the list, as a script the app
 *    loads. The Android app installs Compact from it on request — into its
 *    own storage on the device — rather than carrying 135 MB in every APK.
 *
 * 3. Exports the files to app/data/mt/ for the copies that do carry them —
 *    the app opened from this folder, and the web build: base64 in pieces of
 *    a few megabytes, each piece a script (HSKKER_MT(file, piece, data)),
 *    since a page opened straight from disk (file://) may not fetch a file
 *    but may load a script. index.js says what there is. The APK leaves this
 *    folder out (android/app/build.gradle, ignoreAssetsPattern).
 *
 * Nothing in app/data/mt/ or app/data/translation-files.js is edited by
 * hand; both are made again from data/translation/ at any time.
 */
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { TRANSLATION } from './lib/paths.mjs'

const LIST = JSON.parse(readFileSync(`${TRANSLATION.dir}/files.json`, 'utf8'))
const FILES = LIST.files.map((f) => ({ ...f, src: `${TRANSLATION.dir}/${f.path}` }))
/* bytes of a file to one piece: about 4 MB of script each */
const PIECE = 3 * 1024 * 1024

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex')
const mb = (n) => `${(n / 1048576).toFixed(1)} MB`

/* 1. the files, as published */
for (const f of FILES) {
  if (existsSync(f.src)) {
    const have = readFileSync(f.src)
    if (have.length === f.bytes && sha256(have) === f.sha) { console.log(`  have   ${f.src}`); continue }
    console.log(`  stale  ${f.src} — fetching it again`)
  }
  process.stdout.write(`  fetch  ${f.src} (${mb(f.bytes)})… `)
  const res = await fetch(f.url)
  if (!res.ok) throw new Error(`${f.url}: ${res.status}`)
  const buf = Buffer.from(await res.arrayBuffer())
  if (buf.length !== f.bytes) throw new Error(`${f.src}: ${buf.length} bytes, expected ${f.bytes}`)
  if (sha256(buf) !== f.sha) throw new Error(`${f.src}: SHA-256 does not match — not written`)
  mkdirSync(dirname(f.src), { recursive: true })
  writeFileSync(f.src, buf)
  console.log('checked')
}

/* 2. the list, for the app to install from */
const list = { model: LIST.model, files: LIST.files.map(({ name, path, url, bytes, sha }) => ({ name, path, url, bytes, sha })) }
writeFileSync(TRANSLATION.list,
  '/* Generated by scripts/build-translation.mjs from data/translation/files.json — not edited by hand.\n' +
  '   The offline translator\'s files: what the Android app installs (reader.js mtInstall). */\n' +
  `HSKKER_MT_FILES = ${JSON.stringify(list)};\n`)

/* 3. the scripts the copies that carry it load */
rmSync(TRANSLATION.out, { recursive: true, force: true })
mkdirSync(TRANSLATION.out, { recursive: true })
const index = { version: 1, files: [] }
let written = 0
FILES.forEach((f, i) => {
  const buf = readFileSync(f.src)
  const chunks = []
  for (let k = 0, at = 0; at < buf.length; k++, at += PIECE) {
    const file = `${f.slug}-${String(k).padStart(2, '0')}.js`
    const body = `HSKKER_MT(${i},${k},"${buf.subarray(at, at + PIECE).toString('base64')}");\n`
    writeFileSync(`${TRANSLATION.out}/${file}`, body)
    written += body.length
    chunks.push(file)
  }
  index.files.push({ name: f.name, bytes: f.bytes, sha: f.sha, chunks })
})
writeFileSync(`${TRANSLATION.out}/index.js`,
  '/* Generated by scripts/build-translation.mjs from data/translation/ — not edited by hand.\n' +
  '   The offline translator\'s files and the pieces each is loaded in (reader.js mtShipped). */\n' +
  `HSKKER_MT_INDEX = ${JSON.stringify(index)};\n`)
const pieces = index.files.reduce((n, f) => n + f.chunks.length, 0)
console.log(`\n  ${TRANSLATION.list}: the list of ${FILES.length} files`)
console.log(`  ${TRANSLATION.out}/: ${pieces} pieces, ${mb(written)} of script for ${mb(FILES.reduce((n, f) => n + f.bytes, 0))} of files`)
