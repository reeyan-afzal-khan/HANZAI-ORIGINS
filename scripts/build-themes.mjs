/* build-themes.mjs — compile themes/ into what the app loads.
 *
 *   themes/skins/*.json        ->  app/themes/skins.css    one :root[data-skin] block per file
 *                                  app/themes/themes.js    window.HSKKER_THEMES = {skins, backgrounds}
 *   themes/backgrounds/*.png   ->  app/themes/bg/<id>.png  the texture's alpha, as a mask
 *
 * A theme is a JSON file of tokens (see themes/README.md); the CSS is written
 * from it so that adding a palette is adding a file, not editing a stylesheet
 * in three places. The textures arrive as transparent 4K PNGs — a constant
 * colour with the grain in the alpha channel — so the alpha is all that is
 * kept: downscaled, made to tile without a seam, stretched to the full range,
 * and written twice — a dark grain and a pale one — which the page repeats
 * over the whole window at the texture's own scale, never stretched to fit,
 * the pale one under a dark theme. That way one
 * file serves both light and dark grounds, and a 4K RGBA texture becomes a
 * fraction of its size. Decoding and encoding are done here with node:zlib
 * alone, so the build has no image dependency to install.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync, statSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { inflateSync, deflateSync } from "node:zlib";

const ROOT = dirname(fileURLToPath(import.meta.url)).replace(/[\\/]scripts$/, "");
const SRC  = join(ROOT, "themes");
const OUT  = join(ROOT, "app", "themes");
const LONG = 1536;   // longest side of a shipped mask, in pixels

/* ---------------- skins ---------------- */
const TOKENS = ["void","rail","surface","surface-2","surface-3","line","line-hot","ink","ink-soft","muted",
                "acc","acc-hi","acc-dim","acc-wash","on-acc","stripe","h1","h2","h3","h4","h5","shadow"];

const skinDir = join(SRC, "skins");
const skins = readdirSync(skinDir).filter(f => f.endsWith(".json")).sort().map(f => {
  const sk = JSON.parse(readFileSync(join(skinDir, f), "utf8"));
  if(!/^[a-z0-9-]+$/.test(sk.id || "")) throw new Error(`${f}: id must be a lowercase slug`);
  if(sk.id !== basename(f, ".json")) throw new Error(`${f}: id "${sk.id}" does not match the file name`);
  for(const t of TOKENS) if(!sk.tokens || !sk.tokens[t]) throw new Error(`${f}: missing token "${t}"`);
  if(!Array.isArray(sk.preview) || sk.preview.length !== 5) throw new Error(`${f}: preview needs five colours`);
  return sk;
});
if(!skins.length) throw new Error("themes/skins is empty");

/* Dark themes first, then light, each group by its "order" and then by id —
   the order the picker shows them in, and the first of each group is the
   fallback for a stored theme that no longer exists. */
skins.sort((a, b) => (b.dark ? 1 : 0) - (a.dark ? 1 : 0) || (a.order ?? 99) - (b.order ?? 99) || a.id.localeCompare(b.id));

const css = [`/* Generated by scripts/build-themes.mjs from themes/skins/*.json — edit those, not this. */`];
for(const sk of skins){
  const lines = [`:root[data-skin="${sk.id}"]{`, `  color-scheme:${sk.dark ? "dark" : "light"};`];
  for(const t of TOKENS) lines.push(`  --${t}:${sk.tokens[t]};`);
  lines.push(`  --r:${sk.radius || "13px"};`, `}`);
  css.push(lines.join("\n"));
}

/* ---------------- backgrounds ---------------- */
/* A PNG reader for the one shape these files take: 8-bit, non-interlaced,
   any colour type. Returns the alpha plane, or the luminance when there is no
   alpha, as a Uint8Array of w*h. */
function readMask(buf){
  if(buf.readUInt32BE(0) !== 0x89504E47) throw new Error("not a PNG");
  let pos = 8, w = 0, h = 0, depth = 0, type = 0, interlace = 0;
  const idat = [];
  while(pos < buf.length){
    const len = buf.readUInt32BE(pos), tag = buf.toString("latin1", pos + 4, pos + 8);
    const data = buf.subarray(pos + 8, pos + 8 + len);
    if(tag === "IHDR"){
      w = data.readUInt32BE(0); h = data.readUInt32BE(4);
      depth = data[8]; type = data[9]; interlace = data[12];
    }else if(tag === "IDAT") idat.push(data);
    else if(tag === "IEND") break;
    pos += 12 + len;
  }
  if(depth !== 8) throw new Error(`only 8-bit PNGs are handled (this one is ${depth}-bit)`);
  if(interlace) throw new Error("interlaced PNGs are not handled");
  const channels = {0: 1, 2: 3, 4: 2, 6: 4}[type];
  if(!channels) throw new Error(`unsupported colour type ${type}`);
  const raw = inflateSync(Buffer.concat(idat));
  const stride = w * channels, out = new Uint8Array(w * h);
  let prev = new Uint8Array(stride), cur = new Uint8Array(stride);
  const paeth = (a, b, c) => { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
                               return pa <= pb && pa <= pc ? a : pb <= pc ? b : c; };
  const hasAlpha = type === 4 || type === 6, aOff = channels - 1;
  for(let y = 0; y < h; y++){
    const f = raw[y * (stride + 1)], row = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for(let i = 0; i < stride; i++){
      const a = i >= channels ? cur[i - channels] : 0, b = prev[i], c = i >= channels ? prev[i - channels] : 0;
      let v = row[i];
      if(f === 1) v += a; else if(f === 2) v += b; else if(f === 3) v += (a + b) >> 1; else if(f === 4) v += paeth(a, b, c);
      cur[i] = v & 255;
    }
    for(let x = 0; x < w; x++){
      const o = x * channels;
      out[y * w + x] = hasAlpha ? cur[o + aOff]
                     : channels >= 3 ? (cur[o] * 299 + cur[o + 1] * 587 + cur[o + 2] * 114) / 1000 | 0
                     : cur[o];
    }
    [prev, cur] = [cur, prev];
  }
  return {w, h, px: out};
}

/* Box-filter a plane down so its longest side is `long`. */
function shrink({w, h, px}, long){
  const s = Math.max(w, h) / long;
  if(s <= 1) return {w, h, px};
  const W = Math.round(w / s), H = Math.round(h / s), out = new Uint8Array(W * H);
  for(let Y = 0; Y < H; Y++){
    const y0 = Math.floor(Y * s), y1 = Math.min(h, Math.max(y0 + 1, Math.floor((Y + 1) * s)));
    for(let X = 0; X < W; X++){
      const x0 = Math.floor(X * s), x1 = Math.min(w, Math.max(x0 + 1, Math.floor((X + 1) * s)));
      let sum = 0, n = 0;
      for(let y = y0; y < y1; y++) for(let x = x0; x < x1; x++){ sum += px[y * w + x]; n++; }
      out[Y * W + X] = Math.round(sum / n);
    }
  }
  return {w: W, h: H, px: out};
}

/* Make a plane tile without a seam. The last `bx` columns are cut off and
   faded into the first `bx` — so the left edge of the tile is what used to
   sit just past its right edge, and the next tile over continues it — and
   the same for the rows. A grain loses nothing to this; it is only paper. */
function wrap({w, h, px}, bx, by){
  const W = w - bx, H = h - by, out = new Uint8Array(W * H);
  for(let y = 0; y < H; y++){
    for(let x = 0; x < W; x++){
      let v = px[y * w + x];
      if(x < bx){ const t = x / bx; v = t * v + (1 - t) * px[y * w + x + W]; }
      out[y * W + x] = v;
    }
  }
  for(let y = 0; y < by; y++){
    const t = y / by;
    for(let x = 0; x < W; x++){
      /* The rows past the bottom, wrapped the same way sideways first. */
      let v2 = px[(y + H) * w + x];
      if(x < bx){ const tx = x / bx; v2 = tx * v2 + (1 - tx) * px[(y + H) * w + x + W]; }
      out[y * W + x] = Math.round(t * out[y * W + x] + (1 - t) * v2);
    }
  }
  for(let i = 0; i < out.length; i++) out[i] = Math.round(out[i]);
  return {w: W, h: H, px: out};
}

/* Write an 8-bit grey+alpha PNG whose grey is solid black and whose alpha is
   the plane: a dark grain, laid over the page as an ordinary background
   image (a CSS mask would need a CORS-clean fetch, which file:// cannot
   give), and inverted by the page under a dark theme. The constant grey
   channel costs nothing once filtered and deflated. */
function writeMask({w, h, px}, grey = 0){
  const crcTable = new Int32Array(256);
  for(let n = 0; n < 256; n++){ let c = n; for(let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; crcTable[n] = c; }
  const crc = buf => { let c = -1; for(const b of buf) c = crcTable[(c ^ b) & 255] ^ (c >>> 8); return (c ^ -1) >>> 0; };
  const chunk = (tag, data) => {
    const out = Buffer.alloc(12 + data.length);
    out.writeUInt32BE(data.length, 0); out.write(tag, 4, "latin1"); data.copy(out, 8);
    out.writeUInt32BE(crc(out.subarray(4, 8 + data.length)), 8 + data.length);
    return out;
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; ihdr[9] = 4; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;   // 8-bit, grey+alpha
  /* Sub-filtered rows: grain has no long runs, but neighbouring texels are
     close, and a residual of small values deflates better than the raw. */
  const stride = w * 2, raw = Buffer.alloc((stride + 1) * h);
  for(let y = 0; y < h; y++){
    const o = y * (stride + 1);
    raw[o] = 1;
    for(let x = 0; x < w; x++){
      const a = px[y * w + x], left = x ? px[y * w + x - 1] : 0;
      raw[o + 1 + x * 2] = x ? 0 : grey;         // grey: constant, so the residual is 0
      raw[o + 2 + x * 2] = (a - left) & 255;     // alpha residual
    }
  }
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]),
                        chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, {level: 9})), chunk("IEND", Buffer.alloc(0))]);
}

/* "Texture_03_Handmade_Pulp_TRANSPARENT_4K.png" -> {id:"handmade-pulp", nm:"Handmade pulp", n:3} */
function nameOf(file){
  const stem = basename(file, ".png").replace(/_?(TRANSPARENT|4K|2K|8K|SEAMLESS|TILE)_?/gi, "_");
  const m = /^(?:texture)?_?(\d+)?_?(.*)$/i.exec(stem);
  const words = (m[2] || stem).split(/[_\-\s]+/).filter(Boolean);
  const nm = words.map((w, i) => i ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1).toLowerCase()).join(" ");
  return {id: words.join("-").toLowerCase(), nm, n: m[1] ? +m[1] : 999};
}

const bgDir = join(SRC, "backgrounds");
const bgOut = join(OUT, "bg");
rmSync(OUT, {recursive: true, force: true});
mkdirSync(bgOut, {recursive: true});

const backgrounds = [];
if(existsSync(bgDir)){
  const files = readdirSync(bgDir).filter(f => /\.png$/i.test(f)).sort();
  for(const f of files){
    const {id, nm, n} = nameOf(f);
    const src = readMask(readFileSync(join(bgDir, f)));
    const small = wrap(shrink(src, LONG), Math.round(LONG / 12), Math.round(LONG / 18));
    /* Stretch to the full range: the page sets the strength, so what is kept
       is the pattern, not the file's own faintness. */
    let peak = 1; for(const v of small.px) if(v > peak) peak = v;
    for(let i = 0; i < small.px.length; i++) small.px[i] = Math.round(small.px[i] * 255 / peak);
    /* Two files, the same grain: dark for a light theme, pale for a dark
       one. A second file costs nothing over a CSS filter on the sheet but
       saves the GPU inverting a full-screen layer on every frame. */
    const png = writeMask(small, 0), pale = writeMask(small, 232);
    writeFileSync(join(bgOut, id + ".png"), png);
    writeFileSync(join(bgOut, id + "-light.png"), pale);
    backgrounds.push({id, nm, n, w: small.w, h: small.h, bytes: png.length + pale.length});
    console.log(`  ${f} -> bg/${id}.png + -light.png  ${small.w}x${small.h}  ${(png.length / 1024).toFixed(0)} KB each  (peak alpha ${peak})`);
  }
  backgrounds.sort((a, b) => a.n - b.n || a.id.localeCompare(b.id));
}

/* ---------------- write ---------------- */
const pub = skins.map(sk => ({
  id: sk.id, nm: sk.name, dark: !!sk.dark,
  bg: sk.tokens.void, ac: sk.tokens.acc, rp: sk.preview, r: sk.radius || "13px",
}));
const js = `/* Generated by scripts/build-themes.mjs from themes/ — edit those, not this. */
window.HSKKER_THEMES = ${JSON.stringify({
  skins: pub,
  backgrounds: backgrounds.map(b => ({id: b.id, nm: b.nm, w: b.w, h: b.h, file: "./themes/bg/" + b.id + ".png", fileLight: "./themes/bg/" + b.id + "-light.png"})),
}, null, 1)};
`;
writeFileSync(join(OUT, "skins.css"), css.join("\n") + "\n");
writeFileSync(join(OUT, "themes.js"), js);
const total = backgrounds.reduce((n, b) => n + b.bytes, 0);
console.log(`themes: ${skins.length} skins (${skins.filter(s => s.dark).length} dark, ${skins.filter(s => !s.dark).length} light), ${backgrounds.length} backgrounds, ${(total / 1048576).toFixed(1)} MB of masks -> app/themes/`);
