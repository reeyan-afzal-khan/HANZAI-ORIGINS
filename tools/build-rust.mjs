import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const hash = createHash("sha256");
for(const file of readdirSync(join(root,"src","engine")).sort()){
  hash.update(file).update("\0").update(readFileSync(join(root,"src","engine",file),"utf8").replace(/\r\n/g,"\n"));
}
const header = "// Rust source SHA-256 " + hash.digest("hex") + "\n";
const artifact = join(root, "release/web/js/web-engine.js");
if(process.argv.includes("--check")){
  if(!existsSync(artifact) || !readFileSync(artifact,"utf8").replace(/\r\n/g,"\n").startsWith(header)){
    throw Error("Rust sources have changed. Run npm run build:rust before packaging.");
  }
  process.exit(0);
}
const temp = mkdtempSync(join(tmpdir(), "hanzai-wasm-"));
try {
  const wasm = join(temp, "web.wasm");
  const localRust = join(root,"tools/local/rustup/toolchains/stable-x86_64-pc-windows-msvc/bin/rustc.exe");
  execFileSync(process.env.RUSTC || (existsSync(localRust) ? localRust : "rustc"), [
    "src/engine/web.rs", "--edition=2021", "--crate-type=cdylib", "--target=wasm32-unknown-unknown",
    "-Copt-level=3", "-Clto=yes", "-Ccodegen-units=1", "-Cpanic=abort", "-Cstrip=symbols", "-o", wasm,
  ], { cwd: root, stdio: "inherit" });
  const bytes = readFileSync(wasm).toString("base64");
  // A script payload also works when learners open index.html directly via file://.
  // The engine is decoded on the main thread before the app's scripts run, so
  // it uses the native base64 decoder where there is one and a plain loop
  // elsewhere; Uint8Array.from with a callback per byte cost several times as long.
  const source = header + "// Generated by tools/build-rust.mjs.\n" +
    `const webEngine = (base64 => {\n` +
    `  let bytes;\n` +
    `  if(typeof Uint8Array.fromBase64 === "function") bytes = Uint8Array.fromBase64(base64);\n` +
    `  else{ const text = atob(base64); bytes = new Uint8Array(text.length); for(let i = 0; i < text.length; i++) bytes[i] = text.charCodeAt(i); }\n` +
    `  return new WebAssembly.Instance(new WebAssembly.Module(bytes)).exports;\n` +
    `})("${bytes}");\n` +
    `// UTF-8 markup the engine has written, as a string.\n` +
    `const webText = new TextDecoder();\n` +
    `function engineText(ptr, length){ return webText.decode(new Uint8Array(webEngine.memory.buffer, ptr, length)); }\n`;
  writeFileSync(artifact, source);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
